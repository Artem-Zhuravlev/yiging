import { describe, it, expect, vi, beforeEach } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import ConsultationPage from './ConsultationPage.vue'
import { fetchConsultation, updateConsultation } from '../../entities/consultation/api'
import { fetchHexagram } from '../../entities/hexagram/api'
import { requestInterpretation } from '../../entities/interpretation/api'
import { ApiError } from '../../shared/api/http'
import type { ConsultationDetail } from '../../entities/consultation/model'
import type { Hexagram } from '../../entities/hexagram/model'
import type { Interpretation } from '../../entities/interpretation/model'

vi.mock('../../entities/consultation/api', () => ({
  fetchConsultation: vi.fn(),
  updateConsultation: vi.fn(),
}))

vi.mock('../../entities/hexagram/api', () => ({
  fetchHexagram: vi.fn(),
}))

vi.mock('../../entities/interpretation/api', () => ({
  requestInterpretation: vi.fn(),
}))

vi.mock('vue-router', () => ({
  useRoute: () => ({ params: { id: 'abc-123' } }),
}))

const stubs = { RouterLink: { template: '<a><slot /></a>' } }

function sampleHexagram(kingWenNumber: number): Hexagram {
  return {
    kingWenNumber,
    chineseName: '乾',
    pinyin: 'Qián',
    symbol: '䷀',
    lines: Array.from({ length: 6 }, (_, i) => ({
      position: i + 1,
      polarity: 'yang' as const,
    })),
    upperTrigram: { id: 'Qian', name: 'Qian', chineseName: '乾', pinyin: 'Qián', symbol: '☰' },
    lowerTrigram: { id: 'Qian', name: 'Qian', chineseName: '乾', pinyin: 'Qián', symbol: '☰' },
    judgment: null,
    image: null,
    lineStatements: null,
    relationships: {
      nuclear: { kingWenNumber, chineseName: '乾', pinyin: 'Qián' },
      reversed: { kingWenNumber, chineseName: '乾', pinyin: 'Qián' },
      complement: { kingWenNumber, chineseName: '乾', pinyin: 'Qián' },
    },
  }
}

const sampleConsultation: ConsultationDetail = {
  id: 'abc-123',
  question: 'Should I take the offer?',
  method: 'three_coins',
  primaryHexagram: { kingWenNumber: 1, chineseName: '乾', pinyin: 'Qián' },
  changingLinePositions: [1],
  resultingHexagram: { kingWenNumber: 44, chineseName: '姤', pinyin: 'Gòu' },
  createdAt: '2026-08-14T10:00:00+00:00',
  notes: [{ label: 'before', text: 'Nervous.', createdAt: '2026-08-14T09:00:00+00:00' }],
  tags: ['career'],
  context: null,
  whatHappenedBefore: null,
  whatUserWantsToUnderstand: null,
  backgroundInformation: null,
  initialInterpretation: null,
  outcome: null,
  followUpTo: null,
  followUps: [],
  repeats: { primaryHexagram: [], resultingHexagram: [], changingLines: [] },
}

const sampleInterpretation: Interpretation = {
  summary: 'Hexagram 1 in response to: "Should I take the offer?"',
  coreTheme: 'Khien represents what is great and originating.',
  situation: 'Heaven, in its motion, gives the idea of strength.',
  changingLineMeaning: 'The dragon lying hid in the deep.',
  transition: 'Moving toward hexagram 44.',
  practicalReflection: 'This is a placeholder reflection.',
  uncertainties: ['Generated by a mock provider.'],
  sourceReferences: ['Hexagram 1 judgment (Legge, 1899)'],
}

function interpretationButton(wrapper: ReturnType<typeof mount>) {
  return wrapper.findAll('button').find((b) => b.text().includes('Get Interpretation'))!
}

describe('ConsultationPage', () => {
  beforeEach(() => {
    vi.mocked(requestInterpretation).mockClear()
    vi.mocked(updateConsultation).mockClear()
  })

  it('renders the consultation with both hexagram diagrams and marks changing lines', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).toContain('Should I take the offer?')
    expect(wrapper.text()).toContain('Nervous.')
    expect(wrapper.text()).toContain('career')
    expect(wrapper.find('[data-position="1"][data-changing="true"]').exists()).toBe(true)
  })

  it('links to the hexagram comparison page for its primary/resulting pair', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    const compareLink = wrapper.findAll('a').find((a) => a.text() === 'Compare hexagrams')
    expect(compareLink).toBeDefined()
    expect(compareLink!.attributes('to')).toBe('/hexagrams/compare?a=1&b=44')
  })

  it('shows a working "Create Follow-up" link', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    const createFollowUpLink = wrapper.findAll('a').find((a) => a.text() === 'Create Follow-up')
    expect(createFollowUpLink).toBeDefined()
    expect(createFollowUpLink!.attributes('to')).toBe('/consultations/new?followUpTo=abc-123')
  })

  it('shows the follow-up-to link when set', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue({
      ...sampleConsultation,
      followUpTo: { id: 'original-id', question: 'Original question?' },
    })
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).toContain('Follow-up to:')
    const link = wrapper.findAll('a').find((a) => a.text() === 'Original question?')
    expect(link).toBeDefined()
    expect(link!.attributes('to')).toBe('/consultations/original-id')
  })

  it('has no follow-up-to text when unset', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).not.toContain('Follow-up to:')
  })

  it('lists follow-ups linking to each', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue({
      ...sampleConsultation,
      followUps: [
        { id: 'follow-up-1', question: 'First follow-up?' },
        { id: 'follow-up-2', question: 'Second follow-up?' },
      ],
    })
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).toContain('Follow-ups')
    const firstLink = wrapper.findAll('a').find((a) => a.text() === 'First follow-up?')
    const secondLink = wrapper.findAll('a').find((a) => a.text() === 'Second follow-up?')
    expect(firstLink!.attributes('to')).toBe('/consultations/follow-up-1')
    expect(secondLink!.attributes('to')).toBe('/consultations/follow-up-2')
  })

  it('renders each non-empty repeats category as a distinctly labeled linked list', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue({
      ...sampleConsultation,
      repeats: {
        primaryHexagram: [{ id: 'p-1', question: 'Same primary before?' }],
        resultingHexagram: [{ id: 'r-1', question: 'Same resulting before?' }],
        changingLines: [{ id: 'c-1', question: 'Same changing lines before?' }],
      },
    })
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).toContain('Same primary hexagram before')
    expect(wrapper.text()).toContain('Same resulting hexagram before')
    expect(wrapper.text()).toContain('Same changing lines before')

    const primaryLink = wrapper.findAll('a').find((a) => a.text() === 'Same primary before?')
    const resultingLink = wrapper.findAll('a').find((a) => a.text() === 'Same resulting before?')
    const changingLink = wrapper.findAll('a').find((a) => a.text() === 'Same changing lines before?')
    expect(primaryLink!.attributes('to')).toBe('/consultations/p-1')
    expect(resultingLink!.attributes('to')).toBe('/consultations/r-1')
    expect(changingLink!.attributes('to')).toBe('/consultations/c-1')
  })

  it('shows no repeats section at all when all three categories are empty', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).not.toContain('Same primary hexagram before')
    expect(wrapper.text()).not.toContain('Same resulting hexagram before')
    expect(wrapper.text()).not.toContain('Same changing lines before')
  })

  it('pre-fills the context form from the loaded consultation', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue({
      ...sampleConsultation,
      context: 'Existing context.',
    })
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    const textarea = wrapper.find('#edit-context').element as HTMLTextAreaElement
    expect(textarea.value).toBe('Existing context.')
  })

  it('saves the context form and updates the page in place', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(updateConsultation).mockResolvedValue({
      ...sampleConsultation,
      context: 'New context.',
    })

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await wrapper.find('#edit-context').setValue('New context.')
    const contextForm = wrapper.findAll('form')[2]!
    await contextForm.trigger('submit')
    await flushPromises()

    expect(updateConsultation).toHaveBeenCalledWith('abc-123', {
      context: 'New context.',
      whatHappenedBefore: null,
      whatUserWantsToUnderstand: null,
      backgroundInformation: null,
      initialInterpretation: null,
    })
    const textarea = wrapper.find('#edit-context').element as HTMLTextAreaElement
    expect(textarea.value).toBe('New context.')
  })

  it('shows an inline error when saving context fails, without disturbing the rest of the page', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(updateConsultation).mockRejectedValue(new Error('context save failed'))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await wrapper.find('#edit-context').setValue('New context.')
    const contextForm = wrapper.findAll('form')[2]!
    await contextForm.trigger('submit')
    await flushPromises()

    expect(wrapper.text()).toContain('context save failed')
    expect(wrapper.text()).toContain('Should I take the offer?')
  })

  it('pre-fills the outcome form from the loaded consultation', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue({
      ...sampleConsultation,
      outcome: {
        whatActuallyHappened: 'Took the offer.',
        outcome: 'Going well.',
        reflection: null,
        recordedAt: '2026-08-20T09:00:00+00:00',
      },
    })
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    const whatHappened = wrapper.find('#edit-what-happened').element as HTMLTextAreaElement
    const outcomeField = wrapper.find('#edit-outcome').element as HTMLTextAreaElement
    const reflection = wrapper.find('#edit-reflection').element as HTMLTextAreaElement
    expect(whatHappened.value).toBe('Took the offer.')
    expect(outcomeField.value).toBe('Going well.')
    expect(reflection.value).toBe('')
    expect(wrapper.text()).toContain('Last recorded')
  })

  it('has no outcome section content when nothing has been recorded yet', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).not.toContain('Last recorded')
  })

  it('saves the outcome form and updates the page in place', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(updateConsultation).mockResolvedValue({
      ...sampleConsultation,
      outcome: {
        whatActuallyHappened: 'Took the offer.',
        outcome: null,
        reflection: null,
        recordedAt: '2026-08-20T09:00:00+00:00',
      },
    })

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await wrapper.find('#edit-what-happened').setValue('Took the offer.')
    const outcomeForm = wrapper.findAll('form')[3]!
    await outcomeForm.trigger('submit')
    await flushPromises()

    expect(updateConsultation).toHaveBeenCalledWith('abc-123', {
      whatActuallyHappened: 'Took the offer.',
      outcome: null,
      reflection: null,
    })
    expect(wrapper.text()).toContain('Last recorded')
  })

  it('shows an inline error when saving the outcome fails, without disturbing the rest of the page', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(updateConsultation).mockRejectedValue(new Error('outcome save failed'))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await wrapper.find('#edit-what-happened').setValue('Took the offer.')
    const outcomeForm = wrapper.findAll('form')[3]!
    await outcomeForm.trigger('submit')
    await flushPromises()

    expect(wrapper.text()).toContain('outcome save failed')
    expect(wrapper.text()).toContain('Should I take the offer?')
  })

  it('shows "No changing lines" when there are none', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue({
      ...sampleConsultation,
      changingLinePositions: [],
    })
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).toContain('No changing lines')
  })

  it('shows a not-found state on a 404', async () => {
    vi.mocked(fetchConsultation).mockRejectedValue(new ApiError(404, 'Not Found'))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text().toLowerCase()).toContain('not found')
  })

  it('shows a generic error state for other failures', async () => {
    vi.mocked(fetchConsultation).mockRejectedValue(new Error('network down'))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(wrapper.text()).toContain('network down')
  })

  it('does not request an interpretation until the button is clicked', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))

    mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    expect(requestInterpretation).not.toHaveBeenCalled()
  })

  it('requests and renders an interpretation on click', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(requestInterpretation).mockResolvedValue(sampleInterpretation)

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await interpretationButton(wrapper).trigger('click')
    await flushPromises()

    expect(requestInterpretation).toHaveBeenCalledWith('abc-123')
    expect(wrapper.text()).toContain('Khien represents what is great and originating.')
    expect(wrapper.text()).toContain('The dragon lying hid in the deep.')
    expect(wrapper.text()).toContain('Hexagram 1 judgment (Legge, 1899)')
  })

  it('omits changingLineMeaning/transition rows when they are null', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(requestInterpretation).mockResolvedValue({
      ...sampleInterpretation,
      changingLineMeaning: null,
      transition: null,
    })

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()
    await interpretationButton(wrapper).trigger('click')
    await flushPromises()

    expect(wrapper.text()).not.toContain('Changing line meaning')
    expect(wrapper.text()).not.toContain('Transition')
  })

  it('shows an inline error without disturbing the rest of the page', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(requestInterpretation).mockRejectedValue(new Error('interpretation failed'))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()
    await interpretationButton(wrapper).trigger('click')
    await flushPromises()

    expect(wrapper.text()).toContain('interpretation failed')
    expect(wrapper.text()).toContain('Should I take the offer?')
  })

  it('adds a note and clears the form on success', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    const updated = {
      ...sampleConsultation,
      notes: [
        ...sampleConsultation.notes,
        { label: 'after' as const, text: 'Went well.', createdAt: '2026-08-14T11:00:00+00:00' },
      ],
    }
    vi.mocked(updateConsultation).mockResolvedValue(updated)

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await wrapper.find('textarea').setValue('Went well.')
    await wrapper.find('form').trigger('submit')
    await flushPromises()

    expect(updateConsultation).toHaveBeenCalledWith('abc-123', {
      note: { label: 'after', text: 'Went well.' },
    })
    expect(wrapper.text()).toContain('Went well.')
    expect((wrapper.find('textarea').element as HTMLTextAreaElement).value).toBe('')
  })

  it('shows an inline error when adding a note fails, without disturbing the rest of the page', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(updateConsultation).mockRejectedValue(new Error('note rejected'))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await wrapper.find('textarea').setValue('Bad note.')
    await wrapper.find('form').trigger('submit')
    await flushPromises()

    expect(wrapper.text()).toContain('note rejected')
    expect(wrapper.text()).toContain('Should I take the offer?')
  })

  it('adds a tag and clears the form on success', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    const updated = { ...sampleConsultation, tags: [...sampleConsultation.tags, 'clarity'] }
    vi.mocked(updateConsultation).mockResolvedValue(updated)

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    const tagInput = wrapper.find('input[type="text"]')
    await tagInput.setValue('clarity')
    const tagForm = wrapper.findAll('form')[1]
    await tagForm.trigger('submit')
    await flushPromises()

    expect(updateConsultation).toHaveBeenCalledWith('abc-123', { tag: 'clarity' })
    expect(wrapper.text()).toContain('clarity')
    expect((tagInput.element as HTMLInputElement).value).toBe('')
  })

  it('shows an inline error when adding a tag fails, without disturbing the rest of the page', async () => {
    vi.mocked(fetchConsultation).mockResolvedValue(sampleConsultation)
    vi.mocked(fetchHexagram).mockImplementation((n: number) => Promise.resolve(sampleHexagram(n)))
    vi.mocked(updateConsultation).mockRejectedValue(new Error('tag rejected'))

    const wrapper = mount(ConsultationPage, { global: { stubs } })
    await flushPromises()

    await wrapper.find('input[type="text"]').setValue('bad tag')
    const tagForm = wrapper.findAll('form')[1]
    await tagForm.trigger('submit')
    await flushPromises()

    expect(wrapper.text()).toContain('tag rejected')
    expect(wrapper.text()).toContain('Should I take the offer?')
  })
})
